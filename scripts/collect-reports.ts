/**
 * Runs the automated suites and stores their reports under docs/reports/ (versioned with the delivery):
 *
 *   docs/reports/vitest/junit.xml           unit + integration results (JUnit)
 *   docs/reports/vitest/coverage.txt        coverage summary
 *   docs/reports/e2e/                       Playwright HTML report (open index.html)
 *   docs/reports/summary.md                 what ran, when, where and the totals
 *
 *   npm run reports            (add --skip-e2e to keep only the Vitest part)
 *
 * Performance and memory evidence comes from `npm run perf` (docs/reports/performance/).
 */
import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const reportsDirectory = join(root, 'docs', 'reports');
const skipEndToEnd = process.argv.includes('--skip-e2e');

function run(command: string, args: readonly string[]): { readonly status: number; readonly output: string } {
  console.log(`\n$ ${command} ${args.join(' ')}`);
  const result = spawnSync(command, args, { cwd: root, shell: true, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  const output = `${result.stdout}${result.stderr}`;
  process.stdout.write(output);
  return { status: result.status ?? 1, output };
}

function lastMatch(text: string, pattern: RegExp): string {
  const matches = [...text.matchAll(pattern)];
  return matches.at(-1)?.[0]?.trim() ?? 'n/a';
}

mkdirSync(join(reportsDirectory, 'vitest'), { recursive: true });
const vitest = run('npx', [
  'vitest',
  'run',
  '--coverage',
  '--coverage.reporter=text-summary',
  '--reporter=default',
  '--reporter=junit',
  `--outputFile.junit=${join('docs', 'reports', 'vitest', 'junit.xml')}`,
]);
const coverageStart = vitest.output.indexOf('=============================== Coverage summary');
writeFileSync(
  join(reportsDirectory, 'vitest', 'coverage.txt'),
  coverageStart >= 0 ? vitest.output.slice(coverageStart).trim() + '\n' : 'Coverage summary not found.\n',
);

let endToEndLine = 'skipped';
let endToEndStatus = 0;
if (!skipEndToEnd) {
  const endToEnd = run('npx', ['playwright', 'test', '--reporter=list,html']);
  endToEndStatus = endToEnd.status;
  endToEndLine = [lastMatch(endToEnd.output, /\d+ passed[^\n]*/g), lastMatch(endToEnd.output, /\d+ skipped/g)]
    .filter((part) => part !== 'n/a')
    .join(' · ');
  const htmlReport = join(root, 'playwright-report');
  const target = join(reportsDirectory, 'e2e');
  rmSync(target, { recursive: true, force: true });
  if (existsSync(htmlReport)) cpSync(htmlReport, target, { recursive: true });
}

const packageJson = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')) as { version: string };
const summary = `# Test reports

Generated by \`npm run reports\` on ${new Date().toISOString()} (app ${packageJson.version}).

| Item | Value |
| --- | --- |
| Machine | ${os.cpus()[0]?.model.trim() ?? 'unknown'} · ${os.cpus().length} cores · ${Math.round(os.totalmem() / 1024 ** 3)} GB · ${os.type()} ${os.release()} |
| Node.js | ${process.version} |
| Vitest (unit + integration) | ${lastMatch(vitest.output, /Tests\s+[^\n]*/g)} — [junit.xml](vitest/junit.xml), [coverage](vitest/coverage.txt) |
| Playwright (Chromium desktop + mobile) | ${endToEndLine}${skipEndToEnd ? '' : ' — [HTML report](e2e/index.html)'} |
| Performance and memory | [performance/](performance/) — see [docs/PERFORMANCE.md](../PERFORMANCE.md) |
`;
writeFileSync(join(reportsDirectory, 'summary.md'), summary);
console.log(`\nReports written to ${reportsDirectory}`);
process.exitCode = vitest.status !== 0 || endToEndStatus !== 0 ? 1 : 0;
